def dummy_customers(n=100):
    """得意先のダミーデータ（dict の並び）を n 件返す。"""
    rng = random.Random(SEED)
    used = set()
    rows = []
    while len(rows) < n:
        (part, part_kana, romaji), (biz, biz_kana) = rng.choice(_NAME_PARTS), rng.choice(_BUSINESS)
        if (part, biz) in used:
            continue
        used.add((part, biz))
        legal, prefix = rng.choice(_LEGAL_FORMS)
        name = f"{legal}{part}{biz}" if prefix else f"{part}{biz}{legal}"
        pref, city, area_code = rng.choice(_AREAS)
        no = len(rows) + 1
        rows.append({
            "code": f"C{no:03d}",
            "name": name,
            "kana": f"{part_kana}{biz_kana}",
            "postal_code": f"{rng.randint(100, 999)}-{rng.randint(0, 9999):04d}",
            "address": f"{pref}{city}{rng.randint(1, 5)}-{rng.randint(1, 20)}-{rng.randint(1, 30)}",
            "phone": f"{area_code}-0000-{no:04d}",
            "email": f"info{no:03d}@{romaji}.example.com",
            "closing_day": rng.choice([31, 31, 31, 31, 20, 25, 15]),
            "collection_month": rng.choice([1, 1, 1, 2]),
            "collection_day": rng.choice([31, 31, 10, 25]),
        })
    return rows


def dummy_products(n=100):
    """商品のダミーデータ（dict の並び）を n 件返す。仕入単価は売価の6〜8割。"""
    rng = random.Random(SEED)
    items = [
        (prefix, rate, name, unit, price)
        for prefix, rate, products in _PRODUCT_CATEGORIES
        for name, unit, price in products
    ][:n]
    counters = {}
    rows = []
    for prefix, rate, name, unit, price in items:
        counters[prefix] = counters.get(prefix, 0) + 1
        cost = int(price * rng.uniform(0.6, 0.8) / 10) * 10
        rows.append({
            "code": f"{prefix}{counters[prefix]:03d}",
            "name": name,
            "unit": unit,
            "sale_price": Decimal(price),
            "purchase_price": Decimal(cost),
            "tax_rate": rate,
        })
    return rows
